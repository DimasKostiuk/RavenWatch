// src/FillPatterns.cs from tools/fill/hugin*.txt and munin*.txt (the 2026-10-28 variety pass: lists continued where the
// ravens had too few lines for how often they speak). Edit the .txt files, run node tools/fillgen.js, bump Patterns.Revision.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, 'fill');
const lines = f => fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/).map(l => l.trim()).filter(Boolean);
const cs = l => '            ' + JSON.stringify(l) + ',';
const group = who => fs.readdirSync(dir).filter(f => f.startsWith(who) && f.endsWith('.txt')).sort();
const all = who => [].concat(...group(who).map(lines));
const body = who => all(who).map(cs).join('\n');
const out = `#if RAVEN_ITEM
namespace HuginWhispers
{
    // More lines where the ravens had too few for how often they speak (rev 103, the variety pass of 2026-10-28): the fight
    // judge, memories, the everyday words on the shoulder, habits and quirks, feeding, dirt, orders, passing ravens, wishes,
    // home, visits, the gifts' levels, «Жертва». Only lists continued here (a list may go on in any file): no new themes.
    // GENERATED by tools/fillgen.js from tools/fill/hugin*.txt and munin*.txt: edit those, not this file.
    internal static class FillPatterns
    {
        internal static readonly string[] Hugin =
        {
${body('hugin')}
        };

        internal static readonly string[] Munin =
        {
${body('munin')}
        };
    }
}
#endif
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'FillPatterns.cs'), out);
console.log('FillPatterns.cs:', all('hugin').length, 'Hugin /', all('munin').length, 'Munin lines');

// the English lines (tools/fill/en/hugin*.txt, munin*.txt) go into the built-in English phrase files, between two marks
// (written again on every run; a list may be continued anywhere in a phrase file)
const en = path.join(dir, 'en'), langDir = path.join(__dirname, '..', 'assets', 'lang', 'English');
const BEGIN = '# --- more lines where too few (rev 103, tools/fillgen.js) ---', END = '# --- end of rev 103 lines ---';
for (const who of ['hugin', 'munin']) {
  if (!fs.existsSync(en)) break;
  const parts = fs.readdirSync(en).filter(f => f.startsWith(who) && f.endsWith('.txt')).sort();
  const lines = [].concat(...parts.map(f => fs.readFileSync(path.join(en, f), 'utf8').split(/\r?\n/).map(l => l.trim()).filter(Boolean)));
  const file = path.join(langDir, who + '_patterns.txt');
  let text = fs.readFileSync(file, 'utf8');
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  if (a >= 0 && b > a) text = text.slice(0, a) + text.slice(b + END.length);
  text = text.replace(/\s*$/, '') + '\n\n' + BEGIN + '\n' + lines.join('\n') + '\n' + END + '\n';
  fs.writeFileSync(file, text);
  console.log('English ' + who + ':', lines.length, 'lines');
}
