        // where its trouble is now (null: it is in none — or it is hired, a person like any other)
        internal static string State(NpcActor a)
        {
            ZDO z = a != null ? a.Zdo : null;
            if (z == null || NpcTalk.Hired(a)) return null;
            string kind = z.GetString(NpcRescue.KKind, "");
            if (kind.Length == 0) return null;
            int stage = z.GetInt(NpcRescue.KStage, 0);
            if (stage == 2) return "saved";
            if (stage != 1) return null; // (not set up yet, or dead, or its time ran out: no words of its trouble)
            bool foes = NpcLevers.Flag(a, "foes");
            switch (kind)
            {
                case "ambush": return NpcLevers.Flag(a, "ambush") ? "ambush_bait" : foes ? "ambush_foes" : "ambush";
                case "surrounded": case "chased": case "giant": case "captive": case "wounded": case "lost": return foes ? kind + "_foes" : kind;
                default: return kind;
            }
        }

        internal static string Greet(NpcActor a) { return Pick(Greets, State(a)); }
        internal static string More(NpcActor a) { return Pick(Mores, State(a)); }
        internal static string Thanks() { return Pick(Greets, "saved"); }

        private static string Pick(Dictionary<string, string[]> from, string state)
        {
            string[] l;
            if (state == null || !from.TryGetValue(state, out l) || l.Length == 0) return null;
            return Lang.T(l[Random.Range(0, l.Length)]);
        }

